-- 1) AJ EDI 작업장 마스터 (센터·사업장·업체·시공팀 약 490곳)
CREATE TABLE IF NOT EXISTS aj_workplace (
  no           INT PRIMARY KEY,          -- EDI 작업장 번호(demdNumb)
  name         TEXT NOT NULL,
  kind         TEXT,                     -- 센터 / 시공팀 / 업체
  closed       BOOLEAN DEFAULT false,    -- (폐쇄) 표시
  last_synced  DATE,                     -- 재고 데이터를 마지막으로 받은 거래일
  pms_center   TEXT,                     -- PMS 센터와 연결(선택)
  partner_code TEXT                      -- PMS 거래처와 연결(선택)
);
ALTER TABLE aj_workplace ADD COLUMN IF NOT EXISTS sync_enabled BOOLEAN DEFAULT false;  -- 자동 동기화 대상

-- 2) 일별 재고 (EDI 재고조회 1행 = 일자 × 작업장 × 제품)
CREATE TABLE IF NOT EXISTS aj_stock_daily (
  stoc_date    DATE NOT NULL,
  workplace_no INT  NOT NULL,
  item         TEXT NOT NULL,            -- 14C / 18F / 12A / 15A / 23E
  last_stoc    INT DEFAULT 0,            -- 전일재고
  rental_in    INT DEFAULT 0,            -- 렌탈입고(AJ→)
  move_in      INT DEFAULT 0,            -- 이동입고
  move_out     INT DEFAULT 0,            -- 이동출고
  return_out   INT DEFAULT 0,            -- 반납/회수
  this_stoc    INT DEFAULT 0,            -- 금일재고
  raw          JSONB,                    -- EDI 원본 전체 컬럼(계약재고 등 보존)
  synced_at    TIMESTAMPTZ DEFAULT now(),
  PRIMARY KEY (stoc_date, workplace_no, item)
);
CREATE INDEX IF NOT EXISTS aj_stock_daily_wp ON aj_stock_daily (workplace_no, stoc_date);

-- 3) 동기화 이력
CREATE TABLE IF NOT EXISTS aj_sync_log (
  id         BIGSERIAL PRIMARY KEY,
  ran_at     TIMESTAMPTZ DEFAULT now(),
  from_date  DATE, to_date DATE,
  workplaces INT, rows_upserted INT,
  status     TEXT, note TEXT
);

-- 4) 권한: 조회=내부직원, 쓰기=관리자(동기화 스크립트는 service_role 키라 RLS 우회)
ALTER TABLE aj_workplace   ENABLE ROW LEVEL SECURITY;
ALTER TABLE aj_stock_daily ENABLE ROW LEVEL SECURITY;
ALTER TABLE aj_sync_log    ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "ajwp select" ON aj_workplace;
CREATE POLICY "ajwp select" ON aj_workplace FOR SELECT TO authenticated USING (is_internal());
DROP POLICY IF EXISTS "ajwp write" ON aj_workplace;
CREATE POLICY "ajwp write" ON aj_workplace FOR ALL TO authenticated USING (my_role() = '관리자') WITH CHECK (my_role() = '관리자');
DROP POLICY IF EXISTS "ajst select" ON aj_stock_daily;
CREATE POLICY "ajst select" ON aj_stock_daily FOR SELECT TO authenticated USING (is_internal());
DROP POLICY IF EXISTS "ajst write" ON aj_stock_daily;
CREATE POLICY "ajst write" ON aj_stock_daily FOR ALL TO authenticated USING (my_role() = '관리자') WITH CHECK (my_role() = '관리자');
DROP POLICY IF EXISTS "ajlog select" ON aj_sync_log;
CREATE POLICY "ajlog select" ON aj_sync_log FOR SELECT TO authenticated USING (is_internal());

